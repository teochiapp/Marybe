'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const dbName = `test-menu-header-${process.pid}-${Date.now()}.db`;
const dbPath = path.join(__dirname, '..', '.tmp', dbName);
fs.mkdirSync(path.dirname(dbPath), { recursive: true });
process.env.DATABASE_CLIENT = 'sqlite';
process.env.DATABASE_FILENAME = `.tmp/${dbName}`;
process.env.APP_KEYS ||= 'test-menu-one,test-menu-two';
process.env.API_TOKEN_SALT ||= 'test-menu-api';
process.env.ADMIN_JWT_SECRET ||= 'test-menu-admin';
process.env.TRANSFER_TOKEN_SALT ||= 'test-menu-transfer';
process.env.JWT_SECRET ||= 'test-menu-jwt';

test('borrador y publicación conservan relaciones y áreas independientes en Strapi', { timeout: 120000 }, async () => {
  const app = await require('@strapi/strapi').createStrapi().load();
  try {
    const category = await app.documents('api::categoria.categoria').create({ status: 'published', data: { nombre: 'Prueba', seccion: 'Hogar' } });
    const perfume = await app.documents('api::categoria.categoria').create({ status: 'published', data: { nombre: 'Fragancias', seccion: 'Perfumería' } });
    const duplicate = await app.documents('api::categoria.categoria').create({ status: 'published', data: { nombre: 'Prueba', seccion: 'Perfumería' } });
    const product = await app.documents('api::producto.producto').create({ status: 'published', data: { nombre: 'Producto', id_original: 'MENU-TEST', publicado: true, precio: 100, seccion: 'Hogar', categoria: category.documentId } });
    await app.documents('api::ordenamiento-menu-header.ordenamiento-menu-header').create({ data: { categoriasHogar: [category.documentId] } });
    await app.documents('api::menu-lanzamientos-ofertas.menu-lanzamientos-ofertas').create({ data: { ofertas: { titulo_descuentos: 'Original', columnas_categorias: [{ titulo_columna: 'Columna', categorias: [category.documentId] }], productos_destacados: [product.documentId] }, lanzamientos: { titulo_categorias: 'Novedades', categorias: [category.documentId] } } });
    const service = app.service('api::menu-header-admin.menu-header-admin');
    let state = await service.overview();
    assert.deepEqual(state.areas.hogar.published.orden, ['ofertas', 'lanzamientos', `categoria:${category.documentId}`]);
    const order = { orden: [`categoria:${category.documentId}`, 'lanzamientos', 'ofertas'] };
    state = await service.save('hogar', { version: state.version, data: order, publish: false });
    assert.deepEqual(state.areas.hogar.draft, { ...order, ocultos: [] });
    assert.equal(state.areas.hogar.published.orden[0], 'ofertas');
    await assert.rejects(service.save('hogar', { version: 'stale', data: order, publish: true }), { status: 409 });
    state = await service.save('hogar', { version: state.version, data: order, publish: true });
    assert.deepEqual(state.areas.hogar.published.orden, order.orden);
    assert.equal(state.menuCategories.hogar[0].documentId, category.documentId);
    const simultaneous = await Promise.allSettled([
      service.save('hogar', { version: state.version, data: order, publish: false }),
      service.save('hogar', { version: state.version, data: order, publish: false }),
    ]);
    assert.equal(simultaneous.filter(result => result.status === 'fulfilled').length, 1);
    assert.equal(simultaneous.find(result => result.status === 'rejected').reason.status, 409);
    state = await service.overview();
    state = await service.discard('hogar', state.version);
    assert.equal(state.areas.hogar.draft, null);
    const ofertas = { ...state.areas.ofertas.published, titulo_descuentos: 'Promociones' };
    state = await service.save('ofertas', { version: state.version, data: ofertas, publish: true });
    assert.equal(state.areas.ofertas.published.titulo_descuentos, 'Promociones');
    assert.deepEqual(state.areas.ofertas.published.columnas_categorias[0].categorias, [category.documentId]);
    assert.deepEqual(state.areas.ofertas.published.productos_destacados, [product.documentId]);
    assert.equal(state.areas.lanzamientos.published.titulo_categorias, 'Novedades');
    const lanzamientos = { ...state.areas.lanzamientos.published, titulo_categorias: 'Nuevos productos', productos_destacados: [product.documentId] };
    state = await service.save('lanzamientos', { version: state.version, data: lanzamientos, publish: true });
    assert.equal(state.areas.lanzamientos.published.titulo_categorias, 'Nuevos productos');
    assert.equal(state.areas.ofertas.published.titulo_descuentos, 'Promociones');
    const extended = { orden: [...order.orden, `categoria:${perfume.documentId}`] };
    state = await service.save('hogar', { version: state.version, data: extended, publish: false });
    assert.equal(state.menuCategories.hogar.length, 1);
    assert.deepEqual(state.areas.hogar.draft, { ...extended, ocultos: [] });
    state = await service.save('hogar', { version: state.version, data: extended, publish: true });
    assert.deepEqual(state.areas.hogar.published.orden, extended.orden);
    assert.deepEqual(state.menuCategories.hogar.map(item => item.documentId), [category.documentId, perfume.documentId]);
    assert.deepEqual(state.menuCategories.perfumeria, []);
    const bothSections = { orden: [...extended.orden, `categoria:${duplicate.documentId}`] };
    state = await service.save('hogar', { version: state.version, data: bothSections, publish: false });
    assert.deepEqual(state.areas.hogar.draft, { ...bothSections, ocultos: [] });
    state = await service.save('hogar', { version: state.version, data: bothSections, publish: true });
    assert.deepEqual(state.areas.hogar.published.orden, bothSections.orden);
    assert.equal(state.menuCategories.hogar.length, 3);
    const currentOrderDocument = await app.documents('api::ordenamiento-menu-header.ordenamiento-menu-header').findFirst();
    await app.documents('api::ordenamiento-menu-header.ordenamiento-menu-header').update({ documentId: currentOrderDocument.documentId, data: { borradoresMenu: { hogar: { data: extended, baseCategorias: state.menuCategories.hogar.map(item => item.documentId) } } } });
    state = await service.overview();
    assert.deepEqual(state.areas.hogar.draft.orden, bothSections.orden);
    state = await service.discard('hogar', state.version);
    await assert.rejects(service.save('hogar', { version: state.version, data: { orden: [...extended.orden, 'categoria:inexistente'] }, publish: true }), { status: 409 });
    const replaced = { orden: ['ofertas', 'lanzamientos', `categoria:${duplicate.documentId}`, `categoria:${perfume.documentId}`] };
    state = await service.save('hogar', { version: state.version, data: replaced, publish: false });
    assert.deepEqual(state.areas.hogar.published.orden, bothSections.orden);
    state = await service.save('hogar', { version: state.version, data: replaced, publish: true });
    assert.deepEqual(state.areas.hogar.published.orden, replaced.orden);
    assert.deepEqual(new Set(state.menuCategories.hogar.map(item => item.documentId)), new Set([duplicate.documentId, perfume.documentId]));
    assert.deepEqual(state.menuCategories.perfumeria, []);
    state = await service.save('hogar', { version: state.version, data: extended, publish: true });
    assert.deepEqual(state.areas.hogar.published.orden, extended.orden);
    assert.deepEqual(new Set(state.menuCategories.hogar.map(item => item.documentId)), new Set([category.documentId, perfume.documentId]));
    state = await service.save('hogar', { version: state.version, data: extended, publish: false });
    const orderDocument = await app.documents('api::ordenamiento-menu-header.ordenamiento-menu-header').findFirst();
    await app.documents('api::ordenamiento-menu-header.ordenamiento-menu-header').update({ documentId: orderDocument.documentId, data: { categoriasHogar: [category.documentId, perfume.documentId, duplicate.documentId] } });
    state = await service.overview();
    await assert.rejects(service.save('hogar', { version: state.version, data: extended, publish: true }), { status: 409 });
    await assert.rejects(service.save('hogar', { version: state.version, data: extended, publish: false }), { status: 409 });
    state = await service.discard('hogar', state.version);
    await app.documents('api::ordenamiento-menu-header.ordenamiento-menu-header').update({ documentId: orderDocument.documentId, data: { categoriasHogar: [category.documentId, perfume.documentId] } });
    state = await service.overview();
    await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
    const url = `http://127.0.0.1:${app.server.httpServer.address().port}/api/menu-header-admin`;
    assert.equal((await fetch(url)).status, 401);
    const token = require('jsonwebtoken').sign({ isAdminImport: true }, process.env.JWT_SECRET);
    const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' };
    const response = await fetch(url, { headers });
    assert.equal(response.status, 200);
    const fromHttp = (await response.json()).data;
    const saved = await fetch(`${url}/lanzamientos`, { method: 'PUT', headers, body: JSON.stringify({ version: fromHttp.version, data: lanzamientos, publish: false }) });
    assert.equal(saved.status, 200, await saved.clone().text());
    const role = await app.db.query('plugin::users-permissions.role').findOne({ where: { type: 'public' } });
    await app.db.query('plugin::users-permissions.permission').create({ data: { action: 'api::ordenamiento-menu-header.ordenamiento-menu-header.find', role: role.id } });
    const publicResponse = await fetch(`http://127.0.0.1:${app.server.httpServer.address().port}/api/ordenamiento-menu-header`);
    const publicBody = await publicResponse.json();
    assert.equal(publicResponse.status, 200);
    assert.equal(publicBody.data.borradoresMenu, undefined);
    assert.deepEqual(publicBody.data.ordenVisual.hogar, extended.orden);
    assert.deepEqual(publicBody.data.ordenVisual.categoriasAgregadas.hogar, [perfume.documentId, category.documentId]);
    state = await service.overview();
    const hidden = { ...extended, ocultos: ['ofertas', 'lanzamientos'] };
    state = await service.save('hogar', { version: state.version, data: hidden, publish: false });
    assert.deepEqual(state.areas.hogar.draft.ocultos, hidden.ocultos);
    assert.deepEqual(state.areas.hogar.published.ocultos, []);
    state = await service.save('hogar', { version: state.version, data: hidden, publish: true });
    assert.deepEqual(state.areas.hogar.published.ocultos, hidden.ocultos);
    assert.deepEqual(state.areas.perfumeria.published.ocultos, []);
    const updatedPublic = await (await fetch(`http://127.0.0.1:${app.server.httpServer.address().port}/api/ordenamiento-menu-header`)).json();
    assert.deepEqual(updatedPublic.data.ordenVisual.especialesOcultos.hogar, hidden.ocultos);
  } finally {
    await app.destroy();
    if (fs.existsSync(dbPath)) fs.unlinkSync(dbPath);
  }
});
