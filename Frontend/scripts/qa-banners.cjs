// Browser verification using a mocked CMS. Never saves or publishes real data.
// node scripts/qa-banners.cjs <path-to-playwright-package> [base-url]
const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const baseUrl = process.argv[3] || 'http://localhost:3000';
const output = path.resolve(__dirname, '../tmp/banners-qa');
const image = { id: 3, url: '/inicio/featured.webp', name: 'Fragancias.webp', width: 1200, height: 600 };
const banner = { id: 2, titulo: 'Una nueva forma\nde sentir Marybe.', subtitulo: 'Fragancias que cuentan tu historia.', texto_boton: 'Descubrir colección', enlace: '/tienda', mostrar_texto: true, imagen_desktop: image, imagen_mobile: { ...image, url: '/inicio/fragancias-mobile.webp' }, diseno: { desktop: { height: 480, fit: 'cover', background: '#560203', overlay: .35, textX: 5, textY: 50, textWidth: 65, fontSize: 44 }, mobile: { height: 380, textWidth: 90, textX: 2, fontSize: 30 } } };
let group = { documentId: 'qa-promo', updatedAt: 'v1', titulo: 'Campaña de primavera', seccion: 'Perfumería', Filas: [{ id: 1, __component: 'layout.fila-1-columna', diseno: { desktop: { columns: 1 } }, banners: [banner] }] };
const seasonal = { ...group, documentId: 'qa-seasonal', titulo: 'Promociones de temporada', Filas: [{ ...group.Filas[0], id: 10, banners: [{ ...banner, id: 11, titulo: 'Fragancias para cada día', imagen_desktop: { ...image, url: '/inicio/discountedSection.webp' } }] }] };
const home = { ...group, documentId: 'qa-home', seccion: 'Hogar', titulo: 'Hogar principal', Filas: [{ ...group.Filas[0], id: 20, banners: [{ ...banner, id: 21, titulo: 'Tu espacio, tu hogar', imagen_desktop: { ...image, url: '/inicio/featuredSectionHogar.webp' } }] }] };
const main = { documentId: 'qa-main', updatedAt: 'm1', secciones: [] };
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1512, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/**', async route => {
      const url = new URL(route.request().url());
      if (url.pathname === '/api/banners-admin') return route.fulfill({ json: { data: { promotions: [group, seasonal, home], main } } });
      if (url.pathname === '/api/banners-admin/media') return route.fulfill({ json: { data: [image] } });
      if (url.pathname.includes('/api/banners-admin/promociones/')) {
        const body = route.request().postDataJSON();
        assert.equal(body.data.Filas[0].banners[0].diseno.mobile.height, 420);
        group = { ...body.data, documentId: 'qa-promo', updatedAt: 'v2' };
        return route.fulfill({ json: { data: group } });
      }
      return route.fulfill({ json: { data: null } });
    });
    await page.goto(`${baseUrl}/banners-admin`);
    await page.getByText('Panel de Banners', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'login.png'), fullPage: true });
    await context.addInitScript(() => localStorage.setItem('admin_jwt', 'qa-only-fixture-token'));
    await page.reload();
    await page.getByRole('combobox', { name: 'Plantilla de distribución' }).waitFor();
    await page.screenshot({ path: path.join(output, 'editor-distribucion.png'), fullPage: true });
    await page.locator('.ba-layer-banner-select').first().click();
    await page.getByText('Tamaño y encuadre · Computadora').click();
    await page.getByText('Diseño de textos').click();
    await page.getByText('Visibilidad', { exact: true }).click();
    await page.getByRole('spinbutton', { name: 'Alto', exact: true }).waitFor();
    const preview = page.frameLocator('iframe[title="Vista previa de banners"]');
    await preview.locator('.vb-banner').waitFor();
    await page.getByRole('button', { name: 'Expandir Promociones de temporada' }).click();
    await page.screenshot({ path: path.join(output, 'editor-desktop.png'), fullPage: true });
    assert.equal(await preview.locator('.vb-banner').evaluate(element => getComputedStyle(element).height), '480px');
    async function markFocal(x, y) {
      await page.getByRole('button', { name: 'Editar encuadre' }).click();
      const layer = preview.getByLabel('Editar punto focal');
      await layer.waitFor();
      const box = await layer.boundingBox();
      await layer.click({ position: { x: box.width * x, y: box.height * y } });
      await layer.press('Escape');
      await page.getByRole('button', { name: 'Editar encuadre' }).waitFor();
      return [await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue(), await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue()];
    }
    const desktopFocal = await markFocal(.2, .25);
    await page.getByRole('button', { name: 'Tablet', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton', { name: 'Alto', exact: true }).inputValue(), '480');
    const tabletFocal = await markFocal(.8, .75);
    assert.notDeepEqual(tabletFocal, desktopFocal);
    await page.screenshot({ path: path.join(output, 'editor-tablet-preview.png'), fullPage: true });
    await page.getByRole('button', { name: 'Celular', exact: true }).click();
    await page.getByRole('button', { name: 'Editar encuadre' }).click();
    const focal = preview.getByLabel('Editar punto focal');
    await focal.waitFor();
    const beforeFocal = [Number(await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue()), Number(await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue())];
    const focalBox = await focal.boundingBox();
    await page.mouse.move(focalBox.x + focalBox.width * 0.5, focalBox.y + focalBox.height * 0.5);
    await page.mouse.down();
    await page.mouse.move(focalBox.x + focalBox.width * 0.6, focalBox.y + focalBox.height * 0.6, { steps: 8 });
    await page.mouse.up();
    await page.waitForFunction(([x, y]) => Number(document.querySelector('input[aria-label="Encuadre horizontal"]').value) !== x || Number(document.querySelector('input[aria-label="Encuadre vertical"]').value) !== y, beforeFocal);
    const changedFocal = [Number(await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue()), Number(await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue())];
    await page.getByRole('button', { name: 'Deshacer' }).click();
    assert.deepEqual([Number(await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue()), Number(await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue())], beforeFocal);
    await page.getByRole('button', { name: 'Rehacer' }).click();
    assert.deepEqual([Number(await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue()), Number(await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue())], changedFocal);
    await page.getByRole('button', { name: 'Volver a heredar Alto', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton', { name: 'Alto', exact: true }).inputValue(), '480');
    assert.equal(Number(await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue()), changedFocal[0]);
    await focal.press('Escape');
    await page.getByRole('button', { name: 'Editar encuadre' }).waitFor();
    const mobileFocal = [await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue(), await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue()];
    await page.getByRole('button', { name: 'Computadora', exact: true }).click();
    assert.deepEqual([await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue(), await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue()], desktopFocal);
    await page.getByRole('button', { name: 'Tablet', exact: true }).click();
    assert.deepEqual([await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue(), await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue()], tabletFocal);
    await page.getByRole('button', { name: 'Celular', exact: true }).click();
    assert.deepEqual([await page.getByRole('spinbutton', { name: 'Encuadre horizontal' }).inputValue(), await page.getByRole('spinbutton', { name: 'Encuadre vertical' }).inputValue()], mobileFocal);
    await page.getByRole('button', { name: 'Editar encuadre' }).click();
    await focal.waitFor();
    await focal.click({ position: { x: 30, y: 30 } });
    await focal.press('Escape');
    await page.getByRole('button', { name: 'Editar encuadre' }).waitFor();
    await page.getByRole('spinbutton', { name: 'Alto', exact: true }).fill('420');
    await page.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.querySelector('.vb-banner')?.style.getPropertyValue('--vb-height-2') === '420px');
    assert.equal(await preview.locator('.vb-banner').evaluate(element => getComputedStyle(element).height), '420px');
    assert.equal(await preview.locator('img').getAttribute('src'), '/inicio/featured.webp');
    assert.ok((await preview.locator('img').evaluate(element => element.currentSrc)).includes('fragancias-mobile.webp'));
    const textBox = await preview.locator('.vb-content').boundingBox();
    await page.mouse.move(textBox.x + 15, textBox.y + 15);
    await page.mouse.down();
    await page.mouse.move(textBox.x + 45, textBox.y + 45, { steps: 8 });
    await page.mouse.up();
    await page.waitForFunction(() => Number(document.querySelector('input[aria-label="Posición horizontal"]').value) > 2);
    await page.getByLabel('Banner activo en todos los dispositivos', { exact: true }).uncheck();
    await preview.locator('.vb-banner').waitFor({ state: 'detached' });
    await page.getByLabel('Banner activo en todos los dispositivos', { exact: true }).check();
    await preview.locator('.vb-banner').waitFor();
    await page.screenshot({ path: path.join(output, 'editor-mobile-preview.png'), fullPage: true });
    await page.getByRole('button', { name: 'Vista previa', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Campaña de primavera' });
    const cleanPreview = dialog.frameLocator('iframe[title="Vista previa limpia de banners"]');
    await cleanPreview.locator('.vb-banner').waitFor();
    assert.equal(await cleanPreview.locator('.vb-edit-label').count(), 0);
    assert.equal(await cleanPreview.locator('.vb-banner--selected').count(), 0);
    assert.equal(await cleanPreview.locator('.vb-banner').evaluate(element => getComputedStyle(element).height), '420px');
    await page.screenshot({ path: path.join(output, 'vista-previa-limpia-mobile.png'), fullPage: true });
    await dialog.getByRole('button', { name: 'Computadora', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('iframe[title="Vista previa limpia de banners"]')?.contentDocument?.querySelector('.vb-banner')?.getBoundingClientRect().height === 480);
    await page.screenshot({ path: path.join(output, 'vista-previa-limpia-desktop.png'), fullPage: true });
    await cleanPreview.getByRole('link', { name: 'Descubrir colección' }).click();
    assert.ok((await dialog.locator('iframe').getAttribute('src')).includes('/banners-preview'));
    await cleanPreview.locator('body').press('Escape');
    await dialog.waitFor({ state: 'detached' });
    assert.equal(await page.getByRole('spinbutton', { name: 'Alto', exact: true }).inputValue(), '420');
    await page.getByRole('button', { name: 'Guardar borrador', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Borrador guardado' }).waitFor();
    await page.getByRole('button', { name: /Cambiar imagen/ }).click();
    await page.getByRole('dialog', { name: 'Biblioteca de imágenes' }).waitFor();
    await page.screenshot({ path: path.join(output, 'biblioteca.png'), fullPage: true });
    await page.getByRole('button', { name: 'Cerrar biblioteca' }).click();
    const structure = page.getByRole('navigation', { name: 'Estructura de banners' });
    assert.equal(await structure.getByRole('button', { name: /^Editar sección:/ }).count(), 2);
    await page.getByRole('button', { name: 'Hogar', exact: true }).click();
    await page.getByRole('button', { name: 'Editar sección: Hogar principal', exact: true }).waitFor();
    assert.equal(await structure.getByRole('button', { name: /^Editar sección:/ }).count(), 1);
    await page.locator('.ba-layer-banner-select').first().click();
    await page.getByRole('spinbutton', { name: 'Alto', exact: true }).fill('390');
    await page.getByRole('button', { name: 'Perfumería', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton', { name: 'Alto', exact: true }).inputValue(), '420');
    await page.getByRole('button', { name: 'Hogar', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton', { name: 'Alto', exact: true }).inputValue(), '390');
    await page.getByRole('button', { name: 'Perfumería', exact: true }).click();
    await page.getByRole('button', { name: 'Contraer Campaña de primavera' }).click();
    await preview.locator('.vb-banner').click({ position: { x: 10, y: 10 } });
    await page.locator('.ba-layer-banner[data-selected="true"]').waitFor();
    const actions = page.getByRole('button', { name: /Acciones de banner: Una nueva forma/ });
    await actions.hover();
    await actions.click();
    await page.getByRole('menuitem', { name: 'Duplicar banner', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'arbol-menu-contextual.png'), fullPage: true });
    await page.keyboard.press('Escape');
    await page.getByRole('menu', { name: 'Acciones del elemento' }).waitFor({ state: 'detached' });
    await actions.press('Enter');
    await page.getByRole('menuitem', { name: 'Renombrar banner', exact: true }).waitFor();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Enter');
    await preview.locator('.vb-banner').nth(1).waitFor();
    await structure.getByRole('button', { name: /Editar banner: Una nueva forma/ }).first().click();
    await page.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.querySelectorAll('.vb-banner')[0]?.classList.contains('vb-banner--selected'));
    await preview.locator('.vb-banner').nth(1).click({ position: { x: 10, y: 10 } });
    await page.waitForFunction(() => document.querySelectorAll('.ba-layer-section.is-current .ba-layer-banner')[1]?.dataset.selected === 'true');
    assert.equal(await structure.getByRole('button', { name: /Editar banner: Una nueva forma/ }).nth(1).getAttribute('aria-pressed'), 'true');
    await structure.getByRole('button', { name: /Acciones de banner: Una nueva forma/ }).nth(1).click();
    await page.getByRole('menuitem', { name: 'Eliminar banner', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('iframe')?.contentDocument?.querySelectorAll('.vb-banner').length === 1);
    assert.equal(await page.getByText('Otras piezas del inicio', { exact: true }).count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'editor-phone.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'El editor móvil no debe desbordarse');
    await page.setViewportSize({ width: 900, height: 1000 });
    await page.screenshot({ path: path.join(output, 'editor-tablet.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'El editor tablet no debe desbordarse');
    await page.setViewportSize({ width: 1512, height: 1000 });
    await page.getByRole('button', { name: 'Computadora', exact: true }).click();
    await page.waitForTimeout(180); // Let the editor's 60 ms preview debounce finish.
    await page.evaluate(payload => document.querySelector('iframe').contentWindow.postMessage({ type: 'MARYBE_BANNERS_PREVIEW', payload }, window.location.origin), {
      device: 'desktop', rows: [{ __component: 'layout.fila-mixta', diseno: { desktop: { columns: 1, gap: 16 } }, banners: [{ ...banner, id: 8, ancho_porcentaje: 50 }, { ...banner, id: 9, ancho_porcentaje: 50 }] }],
    });
    await preview.locator('.vb-cell').nth(1).waitFor();
    const geometry = await preview.locator('.vb-cell').evaluateAll(elements => elements.map(element => ({ top: element.getBoundingClientRect().top, width: element.getBoundingClientRect().width })));
    assert.equal(geometry[0].top, geometry[1].top, '50/50 distribution must fit on one row including the gap');
    assert.ok(geometry[0].width > 500);
    assert.deepEqual(errors, []);
    console.log('Browser QA OK: areas, layer tree, bidirectional selection, keyboard/context menus, primary banners only, clean expanded preview, responsive sizes, Escape return, unsaved edits preserved, image source, drag text, visibility, draft save, library, 50/50 layout.');
    console.log(output);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
